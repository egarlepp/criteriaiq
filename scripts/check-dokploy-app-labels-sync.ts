// Keep the "paste-into-Dokploy-UI" Traefik label snippet in
// `docs/guides/dokploy-traefik-timeouts.md` in lock-step with the
// Compose-mode YAML snippet that lives just above it in the same
// file.
//
// Background (task-672, task-673):
//   Task #672 added a new
//     "## Recommended Traefik labels for Dokploy "Application"
//      (Dockerfile) app type"
//   subsection to `docs/guides/dokploy-traefik-timeouts.md`. It
//   teaches operators on Dokploy's "Application" (Dockerfile) app
//   type — which does NOT read `docker-compose.yml` — how to paste
//   the same six service-port / healthcheck / serversTransport
//   labels into the **Advanced → Labels** UI by hand, with a
//   `<service>` placeholder for the Traefik service name Dokploy
//   auto-generates.
//
//   The Compose-mode YAML snippet immediately above it
//     "## Recommended Traefik snippet for Dokploy"
//   already covers six of the same labels, just with a real service
//   name (`criteriaiq`) and the `- "…"` YAML-list-of-strings
//   formatting Compose expects. That snippet is kept in sync with
//   `docker-compose.yml` by `scripts/check-traefik-snippet-sync.ts`
//   (`npm run lint:traefik`).
//
//   If somebody updates the Compose snippet in the future — e.g.
//   raises `responseHeaderTimeout` from 60s to 120s after a slow-save
//   report — and forgets to also update the new plain-text section,
//   operators following the Dokploy-UI path silently get the old,
//   stale value and re-discover the same 504/502 the guide was
//   written to prevent. This check exists to make that drift loud.
//
// What this check enforces:
//   For each of the six labels in the new "paste-into-Dokploy-UI"
//   snippet (the plain ``` fenced block under
//   "## Recommended Traefik labels for Dokploy "Application"
//   (Dockerfile) app type"), substitute the literal `<service>`
//   placeholder for the real service name used in the Compose
//   snippet (`criteriaiq`) and then assert the resulting label
//   exists verbatim in the Compose snippet's label list (the
//   ```yaml fenced block under "## Recommended Traefik snippet for
//   Dokploy" in the same file).
//
//   This is the "compare each label's *suffix* (everything after
//   the service-name prefix)" requirement from task-673: by aligning
//   the placeholder with the real service name, the comparison
//   reduces to a straight string-equality check on the entire label
//   — port, healthcheck path/interval, transport-name suffix and
//   the timeout values must all match. If any one of them drifts,
//   the substituted Dokploy-UI label will fail to appear in the
//   Compose label list and we report a precise per-label diff.
//
//   Both blocks must contain at least one matching label. An empty
//   extraction is treated as a parse failure, not as "they happen
//   to match".
//
// What this check intentionally does NOT enforce:
//   * The four router-level labels (`traefik.enable=true`,
//     `routers.criteriaiq.rule=…`, `entrypoints=`, `tls.certresolver=`,
//     `routers.criteriaiq.service=`) that ONLY appear in the Compose
//     snippet. The whole point of the Dokploy "Application" subsection
//     is that those are auto-generated by Dokploy from its Domains
//     tab and must NOT be pasted by hand. So the Compose list is
//     allowed to be a strict superset of the Dokploy-UI list.
//   * Surrounding markdown / fence language — the Compose block is
//     ```yaml with `- "…"` list items, the Dokploy-UI block is plain
//     ``` with bare `key=value` lines. This script normalises both
//     into bare label strings and compares those.
//   * Anything outside the labels themselves (the heading wording,
//     the prose around the snippets, etc.).
//
// Source of truth:
//   The Compose snippet is the authoritative copy. It is the one
//   that's already locked to `docker-compose.yml` by
//   `check-traefik-snippet-sync.ts`, and `docker-compose.yml` is
//   what operators actually deploy in Compose mode. When a drift
//   fires, update the new Dokploy-UI subsection to mirror the
//   Compose snippet's values.
//
// Exit code: 0 if every Dokploy-UI label has a matching label in
// the Compose snippet (after `<service>` -> `criteriaiq`
// substitution); 1 with a precise per-label diff and a pointer to
// the docs guide otherwise.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const DOCS_FILE = "docs/guides/dokploy-traefik-timeouts.md";
export const COMPOSE_HEADING = "Recommended Traefik snippet for Dokploy";
export const DOKPLOY_HEADING =
  'Recommended Traefik labels for Dokploy "Application" (Dockerfile) app type';

// The literal placeholder the Dokploy-UI snippet uses where the
// Compose snippet has a real service name. We substitute it for
// the actual service token discovered in the Compose snippet
// (see `inferServiceName` below) before comparing labels across the
// two snippets.
export const SERVICE_PLACEHOLDER = "<service>";

// Fallback service name used when `inferServiceName` cannot find a
// `…services.<name>.loadbalancer.server.port=…` label in the
// Compose snippet (e.g. when the comparator is exercised on a
// minimal synthetic fixture in unit tests). The live docs file
// always provides one, so this fallback only matters for tests.
export const DEFAULT_SERVICE_NAME = "criteriaiq";

export interface SyncResult {
  ok: boolean;
  composeLabels: string[];
  // The service-name token we resolved out of the Compose snippet
  // (or DEFAULT_SERVICE_NAME if the snippet didn't expose one).
  // Substituted into every Dokploy-UI label in place of the
  // literal `<service>` placeholder.
  serviceName: string;
  // The Dokploy-UI labels with `<service>` already substituted, so
  // the diff message shows the labels the operator would actually
  // paste on a real install.
  dokployLabelsExpanded: string[];
  // Populated only when `ok === false`. A short, human-readable
  // explanation of the first divergence we found.
  reason?: string;
}

// Discover the canonical service-name token the Compose snippet
// actually uses, so we don't have to hardcode it. We anchor on the
// `…services.<name>.loadbalancer.server.port=…` label because:
//   * it is the most stable label in the Compose snippet (every
//     Traefik-fronted service must declare its upstream port), and
//   * the `<name>` segment in that label is, by Traefik convention,
//     the same token that gets re-used as the `<name>-transport`
//     prefix on the matching `serversTransports.<name>-transport.…`
//     entries — i.e. exactly what `<service>` stands in for in the
//     Dokploy-UI snippet.
// If the Compose snippet ever drops or renames the service, this
// resolver will pick up the new token automatically. If it can't
// find one at all (e.g. on a minimal test fixture), we fall back
// to DEFAULT_SERVICE_NAME so the comparator still behaves sensibly.
export function inferServiceName(composeLabels: string[]): string {
  for (const label of composeLabels) {
    const m = label.match(
      /^traefik\.http\.services\.([^.]+)\.loadbalancer\.server\.port=/,
    );
    if (m) return m[1];
  }
  return DEFAULT_SERVICE_NAME;
}

// Pull the ordered list of `traefik.…` labels out of the Compose
// snippet (the ```yaml fenced block under
// "## Recommended Traefik snippet for Dokploy" in the docs guide).
// We scan its lines for the `- "traefik.…"` shape; anything else
// inside the fence (the `services:` / `app:` / `labels:`
// scaffolding, blank lines) is ignored.
export function extractComposeSnippetLabels(markdown: string): string[] {
  const headingNeedle = `## ${COMPOSE_HEADING}`;
  const headingIdx = markdown.indexOf(headingNeedle);
  if (headingIdx === -1) {
    throw new Error(
      `Could not find heading "${headingNeedle}" in ${DOCS_FILE}.`,
    );
  }
  const after = markdown.slice(headingIdx);
  const fenceMatch = after.match(/```yaml\r?\n([\s\S]*?)```/);
  if (!fenceMatch) {
    throw new Error(
      `Could not find a \`\`\`yaml fenced code block under ` +
        `"${headingNeedle}" in ${DOCS_FILE}.`,
    );
  }
  const block = fenceMatch[1];
  const labels: string[] = [];
  for (const line of block.split(/\r?\n/)) {
    const m = line.match(/^\s*-\s+"(traefik\..+)"\s*$/);
    if (m) labels.push(m[1]);
  }
  if (labels.length === 0) {
    throw new Error(
      `No \`traefik.…\` labels found inside the fenced YAML block ` +
        `under "${headingNeedle}" in ${DOCS_FILE}.`,
    );
  }
  return labels;
}

// Pull the ordered list of bare `traefik.…` labels out of the
// Dokploy-UI snippet (the plain ``` fenced block — no language tag —
// under "## Recommended Traefik labels for Dokploy "Application"
// (Dockerfile) app type" in the docs guide). The lines inside this
// fence are the literal text operators paste into Dokploy's
// Advanced → Labels UI: bare `key=value`, no leading hyphen, no
// surrounding quotes. Anything else inside the fence (blank lines)
// is ignored.
export function extractDokployUiLabels(markdown: string): string[] {
  const headingNeedle = `## ${DOKPLOY_HEADING}`;
  const headingIdx = markdown.indexOf(headingNeedle);
  if (headingIdx === -1) {
    throw new Error(
      `Could not find heading "${headingNeedle}" in ${DOCS_FILE}.`,
    );
  }
  const after = markdown.slice(headingIdx);
  // Match a fence opened with three backticks followed by a
  // newline (no language tag), so we don't accidentally pick up a
  // ```yaml or ```bash fence that may sit between the heading and
  // the snippet.
  const fenceMatch = after.match(/```\r?\n([\s\S]*?)```/);
  if (!fenceMatch) {
    throw new Error(
      `Could not find a plain \`\`\` fenced code block (no language ` +
        `tag) under "${headingNeedle}" in ${DOCS_FILE}.`,
    );
  }
  const block = fenceMatch[1];
  const labels: string[] = [];
  for (const line of block.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (trimmed === "") continue;
    if (/^traefik\..+=.+$/.test(trimmed)) {
      labels.push(trimmed);
    }
  }
  if (labels.length === 0) {
    throw new Error(
      `No bare \`traefik.…=…\` labels found inside the plain fenced ` +
        `block under "${headingNeedle}" in ${DOCS_FILE}.`,
    );
  }
  return labels;
}

// Substitute every occurrence of `<service>` in a Dokploy-UI label
// for the real service name used in the Compose snippet. After
// substitution the label should be byte-identical to its Compose
// counterpart (same port, same healthcheck path/interval, same
// transport-name suffix, same timeout values).
//
// `serviceName` is normally the value returned by
// `inferServiceName(composeLabels)`. Tests may pass a literal for
// determinism.
export function expandDokployLabel(
  label: string,
  serviceName: string = DEFAULT_SERVICE_NAME,
): string {
  return label.split(SERVICE_PLACEHOLDER).join(serviceName);
}

// Pure comparator. Exposed separately so unit tests can exercise
// the drift-reporting logic without having to materialise temp
// files.
//
// For each Dokploy-UI label (already `<service>` -> SERVICE_NAME
// expanded), assert it appears verbatim in the Compose label list.
// We do NOT require the Dokploy-UI list to cover every Compose
// label — the four router-level labels (rule, entrypoints, TLS,
// service mapping) are intentionally absent from the Dokploy-UI
// snippet, because Dokploy auto-generates them from its Domains
// tab.
export function compareLabels(
  composeLabels: string[],
  dokployLabelsExpanded: string[],
  serviceName: string = DEFAULT_SERVICE_NAME,
): SyncResult {
  const composeSet = new Set(composeLabels);
  for (let i = 0; i < dokployLabelsExpanded.length; i++) {
    const expanded = dokployLabelsExpanded[i];
    if (composeSet.has(expanded)) continue;
    // Find the closest Compose label by shared prefix so the diff
    // message points the reader at the most likely culprit.
    const closest = findClosestByPrefix(expanded, composeLabels);
    const reason = closest
      ? `Dokploy-UI label ${i + 1} has no match in the Compose snippet:\n` +
        `  Dokploy-UI (expanded): ${expanded}\n` +
        `  Closest Compose label: ${closest}`
      : `Dokploy-UI label ${i + 1} has no match in the Compose snippet:\n` +
        `  Dokploy-UI (expanded): ${expanded}\n` +
        `  (no Compose label shares its prefix)`;
    return {
      ok: false,
      composeLabels,
      serviceName,
      dokployLabelsExpanded,
      reason,
    };
  }
  return { ok: true, composeLabels, serviceName, dokployLabelsExpanded };
}

// Pick the Compose label that shares the longest common prefix with
// `target`. Used purely to make drift messages helpful — the result
// has no effect on the pass/fail decision.
function findClosestByPrefix(
  target: string,
  candidates: string[],
): string | undefined {
  let best: string | undefined;
  let bestLen = 0;
  for (const c of candidates) {
    let i = 0;
    while (i < c.length && i < target.length && c[i] === target[i]) i++;
    if (i > bestLen) {
      best = c;
      bestLen = i;
    }
  }
  // Require at least the `traefik.` prefix to call it "closest";
  // otherwise the message is just noise.
  return bestLen >= "traefik.".length ? best : undefined;
}

export interface CheckOptions {
  // Repo root. Defaults to `process.cwd()`.
  root?: string;
}

export function checkDokployAppLabelsSync(
  options: CheckOptions = {},
): SyncResult {
  const root = options.root ?? process.cwd();
  const docs = readFileSync(join(root, DOCS_FILE), "utf8");
  const composeLabels = extractComposeSnippetLabels(docs);
  const serviceName = inferServiceName(composeLabels);
  const dokployLabelsRaw = extractDokployUiLabels(docs);
  const dokployLabelsExpanded = dokployLabelsRaw.map((label) =>
    expandDokployLabel(label, serviceName),
  );
  return compareLabels(composeLabels, dokployLabelsExpanded, serviceName);
}

export function formatReport(result: SyncResult): string {
  if (result.ok) {
    return (
      `OK: every Dokploy-UI label under "${DOKPLOY_HEADING}" has a ` +
      `matching label under "${COMPOSE_HEADING}" in ${DOCS_FILE} ` +
      `(${result.dokployLabelsExpanded.length} label(s) checked, ` +
      `service-name token: \`${result.serviceName}\`).`
    );
  }
  return [
    `FAIL: the Dokploy-UI label snippet under ` +
      `"${DOKPLOY_HEADING}" is out of sync with the Compose snippet ` +
      `under "${COMPOSE_HEADING}" in ${DOCS_FILE}.`,
    "",
    result.reason ?? "(no reason captured)",
    "",
    `Fix: the Compose snippet is the source of truth (it is itself`,
    `kept aligned with docker-compose.yml by`,
    `scripts/check-traefik-snippet-sync.ts). Update the Dokploy-UI`,
    `snippet in ${DOCS_FILE} to mirror the Compose snippet's values`,
    `for port, healthcheck path/interval, serversTransport name and`,
    `forwardingTimeouts (use \`<service>\` where the Compose snippet`,
    `uses the literal \`${result.serviceName}\` service name).`,
  ].join("\n");
}

// CLI entry. Mirrors the convention used by the existing
// `lint:traefik` / `lint:proxy-timeouts` checks: only runs when
// invoked directly (e.g. `tsx scripts/check-dokploy-app-labels-sync.ts`
// or via the `lint:dokploy-app-labels` npm script). When imported
// from a vitest spec the `process.argv[1]` comparison is false and
// nothing executes.
const invokedAsScript = (() => {
  if (!process.argv[1]) return false;
  try {
    return fileURLToPath(import.meta.url) === process.argv[1];
  } catch {
    return false;
  }
})();

if (invokedAsScript) {
  const result = checkDokployAppLabelsSync();
  const report = formatReport(result);
  if (result.ok) {
    console.log(report);
    process.exit(0);
  } else {
    console.error(report);
    process.exit(1);
  }
}
