#!/usr/bin/env tsx
/**
 * scripts/bundle-runtime-docs.ts
 *
 * Bundle the customer-facing markdown docs listed in
 * `server/docs-manifest.ts` into a single JSON blob that ships with the
 * production build (`dist/runtime-docs.json`).
 *
 * Why: the in-app About page documentation viewer
 * (`client/src/pages/about.tsx`) calls `/api/docs/*` routes that used
 * to read `docs/*` straight off disk. The runtime Docker image
 * intentionally does NOT carry the `docs/` tree (task #474, enforced
 * by `scripts/verify-no-internal-docs.sh`), so those routes 404'd in
 * any published deployment. By bundling the content into `dist/` at
 * build time, the runtime can serve the docs without the raw `docs/`
 * directory ever being present in the image.
 *
 * Failure mode: if any source file referenced by the manifest is
 * missing on disk, the script exits non-zero and the build fails.
 * This is intentional — silently dropping a doc would silently break
 * a link on the About page.
 *
 * Output shape (v2): `{ "<source-path>": { content: "<markdown>",
 * posted: "ISO", updated: "ISO" } }`. The earlier `{ source -> string }`
 * shape is still understood by `docs-runtime-loader.ts` for
 * forward/backward-compat with any bundle written by an older script.
 *
 * Posted/updated dates come from the committed `server/doc-dates.json`
 * (generated by `scripts/generate-doc-dates.ts` from `git log`, kept
 * fresh by the `lint:doc-dates` gate). They are NOT computed here via
 * git, because this script runs inside the production Docker build
 * whose context excludes `.git` (see `.dockerignore`) — calling git
 * there returned nulls and was the root cause of "no dates in
 * production". Reading the committed JSON makes the bundle's dates
 * deploy-environment-independent. A source missing from the JSON (or
 * with null dates) just gets the badge omitted.
 *
 * Run via `npm run build` (wired into the build chain). Standalone:
 *   tsx scripts/bundle-runtime-docs.ts
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  docsManifest,
  getDocsManifestSources,
} from "../server/docs-manifest.ts";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const distDir = path.resolve(repoRoot, "dist");
const outFile = path.resolve(distDir, "runtime-docs.json");
const docDatesFile = path.resolve(repoRoot, "server", "doc-dates.json");

const sources = getDocsManifestSources();

interface BundleEntry {
  content: string;
  /** ISO-8601 timestamp of the file's FIRST commit (`null` if unknown). */
  posted: string | null;
  /** ISO-8601 timestamp of the file's MOST RECENT commit (`null` if unknown). */
  updated: string | null;
}

// Load the committed git-derived dates. Absence is non-fatal — the
// bundle just ships without dates (badges omitted) rather than failing
// the build. The lint:doc-dates gate is what guarantees this file is
// present and fresh before a push.
let docDates: Record<string, { posted: string | null; updated: string | null }> = {};
if (existsSync(docDatesFile)) {
  try {
    docDates = JSON.parse(readFileSync(docDatesFile, "utf8"));
  } catch (err) {
    console.warn(
      `[bundle-runtime-docs] could not parse ${path.relative(repoRoot, docDatesFile)}; date badges will be omitted.`,
    );
  }
} else {
  console.warn(
    `[bundle-runtime-docs] ${path.relative(repoRoot, docDatesFile)} not found; date badges will be omitted. Run "npm run docs:dates".`,
  );
}

const missing: string[] = [];
const bundle: Record<string, BundleEntry> = {};

for (const source of sources) {
  const abs = path.resolve(repoRoot, source);
  if (!existsSync(abs)) {
    missing.push(source);
    continue;
  }
  const content = readFileSync(abs, "utf8");
  const dates = docDates[source] ?? { posted: null, updated: null };
  bundle[source] = { content, posted: dates.posted ?? null, updated: dates.updated ?? null };
}

if (missing.length > 0) {
  console.error("");
  console.error(
    `[bundle-runtime-docs] FAIL: ${missing.length} source file(s) referenced by server/docs-manifest.ts do not exist:`,
  );
  for (const m of missing) console.error(`  - ${m}`);
  console.error("");
  console.error(
    "Either remove the entry from server/docs-manifest.ts or add the file at the listed path.",
  );
  console.error("");
  process.exit(1);
}

mkdirSync(distDir, { recursive: true });
writeFileSync(outFile, JSON.stringify(bundle), "utf8");

const totalRoutes = docsManifest.reduce(
  (acc, e) => acc + (e.apiRoutes?.length ?? 0) + (e.htmlRoutes?.length ?? 0),
  0,
);
const serialised = JSON.stringify(bundle);
const totalBytes = Buffer.byteLength(serialised, "utf8");
const datedCount = Object.values(bundle).filter((e) => e.posted !== null).length;

console.log(
  `[bundle-runtime-docs] OK — bundled ${sources.length} doc file(s) ` +
    `(${(totalBytes / 1024).toFixed(1)} KiB) covering ${totalRoutes} route(s) ` +
    `into ${path.relative(repoRoot, outFile)}. ` +
    `Dates present for ${datedCount}/${sources.length} files (from server/doc-dates.json).`,
);
