// Security health calculation
export interface SecurityHealth {
  enabled: boolean;
  method: 'totp' | 'webauthn' | null;
  enrolledAt: string | null;
  recoveryCount: number;
  passkeyCount: number;
  health: 'green' | 'amber' | 'red';
}

export function calculateSecurityHealth(
  mfaEnabled: boolean,
  mfaMethod: string | null,
  mfaEnrolledAt: Date | null,
  recoveryCount: number,
  passkeyCount: number,
  /**
   * OIDC provider the user is linked to (e.g. "okta"). When set AND
   * the admin has flipped `sso_config.require_mfa_trust = true` (the
   * `ssoMfaTrusted` arg), the user counts as fully protected even
   * without CriteriaIQ TOTP / passkey enrollment — Okta's MFA is the
   * actual gate in that path. This matches the OIDC callback's
   * MFA-skip logic so the badge reflects how the user actually
   * authenticates. If `ssoMfaTrusted` is false (admin chose to
   * always run the CriteriaIQ MFA gate on top), the SSO link does
   * NOT promote the health — the user still needs CriteriaIQ MFA.
   */
  ssoProvider: string | null = null,
  ssoMfaTrusted: boolean = false,
): SecurityHealth {
  let health: 'green' | 'amber' | 'red';

  const ssoCoversMfa = !!ssoProvider && ssoMfaTrusted;

  // RED only when MFA is completely disabled AND SSO doesn't cover us
  if (!mfaEnabled && !ssoCoversMfa) {
    health = 'red';
  } else if (ssoCoversMfa) {
    // GREEN when the IdP is enforcing MFA and the admin has trusted
    // it. CriteriaIQ TOTP / recovery / passkey are still useful as a
    // fallback but no longer required to reach green — the IdP path
    // is what the user actually takes.
    health = 'green';
  } else if (recoveryCount > 0 && passkeyCount > 0) {
    // GREEN when MFA enabled + recovery codes + passkeys
    health = 'green';
  } else if (recoveryCount > 0) {
    // AMBER when MFA enabled + recovery codes (passkeys optional)
    health = 'amber';
  } else {
    // AMBER when MFA enabled but no recovery codes yet (still better than no MFA)
    health = 'amber';
  }

  return {
    enabled: mfaEnabled || ssoCoversMfa,
    method: mfaMethod as 'totp' | 'webauthn' | null,
    enrolledAt: mfaEnrolledAt ? mfaEnrolledAt.toISOString() : null,
    recoveryCount,
    passkeyCount,
    health
  };
}

// Temporary token utilities for MFA flows
export interface TempToken {
  userId: string;
  type: 'setup_required' | 'mfa_required';
  expiresAt: Date;
}

export function generateTempToken(userId: string, type: 'setup_required' | 'mfa_required'): string {
  if (!MFA_CONFIG.ENCRYPTION_KEY) {
    throw new Error('ENCRYPTION_KEY not configured - cannot generate temp tokens');
  }

  const payload: TempToken = {
    userId,
    type,
    expiresAt: new Date(Date.now() + 15 * 60 * 1000) // 15 minutes
  };
  
  // Simple JWT-like encoding (in production, use proper JWT)
  const encoded = Buffer.from(JSON.stringify(payload)).toString('base64');
  const signature = crypto.createHmac('sha256', MFA_CONFIG.ENCRYPTION_KEY)
    .update(encoded)
    .digest('hex');
  
  return `${encoded}.${signature}`;
}

export function verifyTempToken(token: string): TempToken | null {
  if (!MFA_CONFIG.ENCRYPTION_KEY) {
    return null;
  }

  try {
    const [encoded, signature] = token.split('.');
    
    // Verify signature
    const expectedSignature = crypto.createHmac('sha256', MFA_CONFIG.ENCRYPTION_KEY)
      .update(encoded)
      .digest('hex');
    
    if (signature !== expectedSignature) {
      return null;
    }
    
    // Decode payload
    const payload = JSON.parse(Buffer.from(encoded, 'base64').toString());
    const tempToken: TempToken = {
      ...payload,
      expiresAt: new Date(payload.expiresAt)
    };
    
    // Check expiration
    if (tempToken.expiresAt < new Date()) {
      return null;
    }
    
    return tempToken;
  } catch (error) {
    return null;
  }
}

// Rate-limiting utilities for the auth surface.
//
// Task #630 moved the canonical bucket store from a process-local
// `Map<string, { failedCount, resetTime }>` to the persistent
// `auth_rate_limits` Postgres table so the budgets survive rolling
// restarts and are shared across workers in a multi-replica deployment.
// Both invariants were silently broken before: a restart wiped every
// locked-out attacker's budget, and a multi-worker deployment let an
// attacker pivot from a closed bucket on worker A to an empty bucket
// on worker B for another N attempts.
//
// The in-memory map below is retained as a *fallback* — used only when
// `dbReady === false` (setup wizard, tests, no DATABASE_URL) or when
// the DB op throws (transient hiccup). The fallback's failure mode is
// "preserve the old single-process behaviour" rather than "open the
// gate". It deliberately stays synchronous-before-await inside the
// async wrapper so that callers which forget to `await` the helper
// (notably the `recordAttemptResult(key, true)` pattern in the
// integration-test fixtures) still observe the mutation immediately
// when the DB is unavailable.
const mfaAttempts = new Map<string, { failedCount: number; resetTime: number }>();

function checkInMemoryRateLimit(identifier: string, maxAttempts: number): boolean {
  const now = Date.now();
  const attempts = mfaAttempts.get(identifier);
  if (!attempts || attempts.resetTime < now) {
    return true;
  }
  return attempts.failedCount < maxAttempts;
}

function recordInMemoryAttemptResult(
  identifier: string,
  success: boolean,
  windowMs: number,
): void {
  const now = Date.now();
  const attempts = mfaAttempts.get(identifier);
  if (success) {
    mfaAttempts.delete(identifier);
    return;
  }
  if (!attempts || attempts.resetTime < now) {
    mfaAttempts.set(identifier, { failedCount: 1, resetTime: now + windowMs });
  } else {
    attempts.failedCount++;
  }
}

function getInMemoryRateLimitResetTime(identifier: string): number | null {
  const attempts = mfaAttempts.get(identifier);
  if (!attempts) return null;
  if (attempts.resetTime < Date.now()) return null;
  return attempts.resetTime;
}

/**
 * Lazy import for the db handle. Imported lazily (not at module load)
 * so this file stays usable inside the setup wizard's pre-DB phase
 * and inside tests that mock or skip `../db` entirely. The import is
 * cached inside the helper after the first successful resolution so
 * the per-request cost is one Map lookup, not a dynamic import each
 * time.
 *
 * Returns `null` when `dbReady` is false (no DATABASE_URL, no
 * data/db-config.json) so the caller knows to fall back to the
 * in-memory map. We don't try to recover from import errors — if
 * `../db` itself can't load, that's a structural failure that the
 * caller's try/catch around the DB op will catch and bridge to the
 * fallback.
 */
let _dbHandleCache: { db: any } | null = null;
async function getRateLimitDbHandle(): Promise<{ db: any } | null> {
  if (_dbHandleCache) return _dbHandleCache;
  try {
    const mod = await import("../db");
    if (!mod.dbReady || !mod.db) return null;
    _dbHandleCache = { db: mod.db };
    return _dbHandleCache;
  } catch {
    return null;
  }
}

/**
 * Returns true if the bucket identified by `identifier` still has
 * room inside the current window — i.e. the caller is permitted to
 * attempt another verification. Returns false once the recorded
 * `failed_count` reaches `maxAttempts` while `reset_at` is still in
 * the future.
 *
 * DB-first: looks up the row by primary key. If the row is missing
 * or its `reset_at` is in the past, the bucket is considered open
 * (a stale row is treated as if it had been pruned). Falls back to
 * the in-memory map when the DB is unavailable so setup-mode and
 * tests continue to work.
 *
 * `windowMs` is accepted for API compatibility with the old
 * signature but is unused by the read path — only the writer
 * (`recordAttemptResult`) needs it to compute `reset_at`.
 */
export async function checkRateLimit(
  identifier: string,
  maxAttempts: number = 5,
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  _windowMs: number = 15 * 60 * 1000,
): Promise<boolean> {
  const handle = await getRateLimitDbHandle();
  if (!handle) {
    return checkInMemoryRateLimit(identifier, maxAttempts);
  }
  try {
    // Inline imports keep the schema dependency out of the cold path
    // that `getRateLimitDbHandle()` already negotiates.
    const { authRateLimits } = await import("@shared/schema");
    const { eq } = await import("drizzle-orm");
    const rows = await handle.db
      .select()
      .from(authRateLimits)
      .where(eq(authRateLimits.bucketKey, identifier))
      .limit(1);
    const row = rows[0];
    if (!row) return true;
    const resetAt = row.resetAt instanceof Date ? row.resetAt : new Date(row.resetAt);
    if (resetAt.getTime() < Date.now()) return true;
    return (row.failedCount ?? 0) < maxAttempts;
  } catch (err) {
    // A transient DB hiccup must NOT open the gate — fall back to
    // the in-memory bucket so we at least preserve single-process
    // brute-force defence while the DB is being pieced back together.
    console.error(
      `[rate-limit] DB read failed for bucket ${identifier}; falling back to in-memory map:`,
      err,
    );
    return checkInMemoryRateLimit(identifier, maxAttempts);
  }
}

/**
 * Returns the unix-epoch millisecond timestamp at which the given
 * rate-limit bucket will reset (i.e. when the failed-attempt counter
 * will be cleared and the user is allowed to try again). Returns
 * `null` if the bucket has no active entry — either because the user
 * has never tripped the limiter or because the window already
 * expired.
 *
 * Exists so callers that want to *communicate* the cooldown to the
 * end user (e.g. /api/login surfacing a `Retry-After` header so the
 * front-end can render "try again in 14:32" instead of the generic
 * "too many attempts" message — Task #629) can read the reset time
 * without reaching into the private `mfaAttempts` map and without
 * having to remember the window length the limiter was configured
 * with.
 *
 * DB-first: looks up the row by primary key in `auth_rate_limits`.
 * If the row is missing or its `reset_at` is in the past, returns
 * `null` (the bucket is no longer active). Falls back to the
 * in-memory map when the DB is unavailable so setup-mode and tests
 * continue to work — and so the value the helper returns is
 * consistent with what `checkRateLimit` actually enforces, since
 * Task #630 made that helper itself fall back to the in-memory map
 * on DB outages.
 */
export async function getRateLimitResetTime(
  identifier: string,
): Promise<number | null> {
  const handle = await getRateLimitDbHandle();
  if (!handle) {
    return getInMemoryRateLimitResetTime(identifier);
  }
  try {
    const { authRateLimits } = await import("@shared/schema");
    const { eq } = await import("drizzle-orm");
    const rows = await handle.db
      .select()
      .from(authRateLimits)
      .where(eq(authRateLimits.bucketKey, identifier))
      .limit(1);
    const row = rows[0];
    if (!row) return null;
    const resetAt = row.resetAt instanceof Date ? row.resetAt : new Date(row.resetAt);
    const resetMs = resetAt.getTime();
    if (resetMs < Date.now()) return null;
    return resetMs;
  } catch (err) {
    // Mirrors the failure semantics of `checkRateLimit`: a DB hiccup
    // shouldn't make the Retry-After header lie, so fall back to the
    // in-memory map's view of the bucket. The user may see a slightly
    // stale countdown but never a wrong one (it can only be too
    // short, never too long).
    console.error(
      `[rate-limit] DB read failed for reset-time lookup of bucket ${identifier}; ` +
        "falling back to in-memory map:",
      err,
    );
    return getInMemoryRateLimitResetTime(identifier);
  }
}

/**
 * Records a single attempt against the bucket identified by
 * `identifier`. A successful attempt deletes the row outright (so
 * the legitimate user gets a fresh budget on their next sign-in
 * after a typo-streak); a failed attempt UPSERTs the row, either
 * starting a new window with `failed_count=1` or incrementing the
 * existing count while preserving the original `reset_at`.
 *
 * Falls back to the in-memory map when the DB is unavailable. The
 * fallback runs synchronously *before* the function awaits anything
 * so callers that forget to `await` (notably the test fixtures that
 * use `recordAttemptResult(key, true)` to clear leftover buckets
 * between tests) still observe the mutation immediately.
 */
export async function recordAttemptResult(
  identifier: string,
  success: boolean,
  windowMs: number = 15 * 60 * 1000,
): Promise<void> {
  // Mirror the mutation into the in-memory fallback FIRST. This is
  // the property the test fixtures depend on: `recordAttemptResult`
  // is called without `await` to clear leftover state, and the very
  // next request must not see the stale bucket. Mirroring also keeps
  // the fallback warm in case the DB op below throws halfway through
  // a streak.
  recordInMemoryAttemptResult(identifier, success, windowMs);

  const handle = await getRateLimitDbHandle();
  if (!handle) {
    return;
  }
  try {
    const { authRateLimits } = await import("@shared/schema");
    const { eq, sql } = await import("drizzle-orm");
    if (success) {
      // Success clears the bucket entirely — the next attempt starts
      // a brand-new window. Matches the old in-memory semantics
      // (`mfaAttempts.delete(identifier)`).
      await handle.db
        .delete(authRateLimits)
        .where(eq(authRateLimits.bucketKey, identifier));
      return;
    }
    // Failure: UPSERT the row. The CASE expressions handle the
    // window-rollover semantics in a single round-trip without a
    // SELECT-then-UPDATE race that two workers could lose to each
    // other:
    //   - If `reset_at` has already passed, treat this attempt as the
    //     start of a fresh window (count=1, new reset_at).
    //   - Otherwise, increment the count and PRESERVE the existing
    //     `reset_at` so the original window keeps shrinking instead of
    //     getting reset by every failed attempt.
    const resetAtCandidate = new Date(Date.now() + windowMs);
    await handle.db
      .insert(authRateLimits)
      .values({
        bucketKey: identifier,
        failedCount: 1,
        resetAt: resetAtCandidate,
      })
      .onConflictDoUpdate({
        target: authRateLimits.bucketKey,
        set: {
          failedCount: sql`CASE
            WHEN ${authRateLimits.resetAt} < NOW() THEN 1
            ELSE ${authRateLimits.failedCount} + 1
          END`,
          resetAt: sql`CASE
            WHEN ${authRateLimits.resetAt} < NOW() THEN ${resetAtCandidate}
            ELSE ${authRateLimits.resetAt}
          END`,
          updatedAt: sql`NOW()`,
        },
      });
  } catch (err) {
    // The in-memory mirror above already absorbed the mutation, so
    // we still bound the brute-force budget within this process even
    // when the DB write fails. Log and move on — the next attempt
    // will retry the DB write, and a sustained DB outage degrades
    // gracefully to the old behaviour.
    console.error(
      `[rate-limit] DB write failed for bucket ${identifier} (success=${success}); ` +
        "kept in-memory mirror in sync, will retry on next attempt:",
      err,
    );
  }
}

// Short-lived HMAC-signed envelope binding a WebAuthn assertion challenge
// to the user it was issued for during the password→MFA login flow.
//
// Why not an in-memory Map? The previous implementation stored the
// challenge in a process-local `Map<userId, {challenge, expiresAt}>`,
// which silently broke in two real production scenarios (Task #611):
//   1. Multi-worker deployments — /api/webauthn/authenticate/begin lands
//      on worker A, /api/mfa/challenge lands on worker B; B's Map is
//      empty so the user sees "Passkey challenge expired".
//   2. Rolling restarts between begin/challenge — the new process starts
//      with an empty Map, same failure mode.
//
// We can't piggy-back on `req.session.webauthnChallenges` (the way
// registration does) because the user is NOT yet logged in here — they
// only hold a short-lived `temporaryToken` (`mfa_required`). So instead
// we sign the challenge into a tiny token using the same HMAC-SHA256 +
// ENCRYPTION_KEY pattern `generateTempToken` already uses, return that
// token from /begin, and have the client echo it back in the body of
// /challenge. The route then verifies signature + expiry + that the
// embedded userId matches the one in the temp token.
//
// Replay protection is preserved by the WebAuthn credential counter
// check inside `verifyAuthenticationResponse` (we bump the stored
// counter on every successful login, so re-submitting the same
// assertion fails the next monotonic-counter check). The 5-minute
// challenge token TTL caps the window an attacker has even before
// the counter check kicks in.
const LOGIN_WEBAUTHN_CHALLENGE_TTL_MS = 5 * 60 * 1000;

interface LoginWebAuthnChallengePayload {
  userId: string;
  challenge: string;
  expiresAt: number;
}

/**
 * Signs the issued WebAuthn assertion `challenge` together with the
 * user it was issued for into a short-lived token. The token MUST be
 * returned to the client (alongside the assertion options) and echoed
 * back to /api/mfa/challenge so the verify path can reconstruct the
 * exact challenge the browser signed without keeping any per-request
 * state on the server. See the block comment above for the rationale.
 */
export function signLoginWebAuthnChallenge(
  userId: string,
  challenge: string,
  ttlMs: number = LOGIN_WEBAUTHN_CHALLENGE_TTL_MS,
): string {
  if (!MFA_CONFIG.ENCRYPTION_KEY) {
    throw new Error(
      'ENCRYPTION_KEY not configured - cannot sign login WebAuthn challenge',
    );
  }
  const payload: LoginWebAuthnChallengePayload = {
    userId,
    challenge,
    expiresAt: Date.now() + ttlMs,
  };
  const encoded = Buffer.from(JSON.stringify(payload)).toString('base64');
  const signature = crypto
    .createHmac('sha256', MFA_CONFIG.ENCRYPTION_KEY)
    .update(encoded)
    .digest('hex');
  return `${encoded}.${signature}`;
}

/**
 * Verifies a token previously produced by `signLoginWebAuthnChallenge`.
 * Returns the embedded challenge string when:
 *   - the HMAC signature is valid (not tampered, not signed by a
 *     rotated/different ENCRYPTION_KEY),
 *   - the embedded `userId` matches `expectedUserId` (so a token issued
 *     for user A cannot be paired with a temp token for user B), and
 *   - the embedded `expiresAt` is still in the future.
 * Returns `null` otherwise so the caller can respond with the same
 * generic "challenge expired — please try again" message.
 */
export function verifyLoginWebAuthnChallengeToken(
  token: string,
  expectedUserId: string,
): string | null {
  if (!MFA_CONFIG.ENCRYPTION_KEY) return null;
  if (!token || typeof token !== 'string') return null;
  try {
    const [encoded, signature] = token.split('.');
    if (!encoded || !signature) return null;

    const expectedSignature = crypto
      .createHmac('sha256', MFA_CONFIG.ENCRYPTION_KEY)
      .update(encoded)
      .digest('hex');
    // Constant-time compare so a malicious caller can't time-side-channel
    // their way to a forged signature.
    const sigBuf = Buffer.from(signature, 'hex');
    const expectedBuf = Buffer.from(expectedSignature, 'hex');
    if (
      sigBuf.length !== expectedBuf.length ||
      !crypto.timingSafeEqual(sigBuf, expectedBuf)
    ) {
      return null;
    }

    const payload = JSON.parse(
      Buffer.from(encoded, 'base64').toString(),
    ) as LoginWebAuthnChallengePayload;
    if (!payload || typeof payload !== 'object') return null;
    if (payload.userId !== expectedUserId) return null;
    if (typeof payload.expiresAt !== 'number') return null;
    if (payload.expiresAt < Date.now()) return null;
    if (typeof payload.challenge !== 'string' || !payload.challenge) {
      return null;
    }
    return payload.challenge;
  } catch {
    return null;
  }
}

// Short-lived HMAC-signed envelope binding a WebAuthn *registration*
// (a.k.a. enrollment) challenge to the user it was issued for.
//
// Why not `req.session.webauthnChallenges`? The previous implementation
// stashed the challenge on `req.session`, which silently broke whenever
// the begin and finish requests landed on different workers (the
// canonical shared session store can lag behind the HMAC-signed cookie
// for a few hundred ms during fail-over) or whenever the session store
// evicted the row before the user finished the WebAuthn ceremony on
// their device — the same multi-worker / restart failure mode Task #611
// fixed for the *login* WebAuthn challenge. Operators saw "challenge
// expired" mid-enrollment for exactly the same reason.
//
// We mirror the login pattern: sign the issued challenge into a tiny
// token using HMAC-SHA256 + ENCRYPTION_KEY, hand it back as an
// HttpOnly cookie that the browser auto-replays on the finish call,
// and verify signature + expiry + that the embedded userId matches the
// one we expect (the session user for self-enrollment, the target user
// for admin-mode enrollment). The token is stateless so it survives
// process restarts and works across multiple workers without sticky
// sessions.
//
// A `purpose: 'registration'` discriminator is baked into the payload
// so a login-flow challenge token (issued by
// `signLoginWebAuthnChallenge`) can never be cross-replayed against
// the registration verifier even if both happened to be bound to the
// same userId — and vice versa. The two flows feed entirely different
// SimpleWebAuthn helpers (registration vs. authentication) so a
// cross-flow token would also fail the underlying crypto check, but
// the discriminator catches it earlier with a clearer audit signal.
const REGISTRATION_WEBAUTHN_CHALLENGE_TTL_MS = 5 * 60 * 1000;

interface RegistrationWebAuthnChallengePayload {
  purpose: "registration";
  userId: string;
  challenge: string;
  expiresAt: number;
}

