export async function verifyWebAuthnAuthentication(
  response: any,
  expectedChallenge: string,
  expectedOrigin: string,
  credentialID: Uint8Array,
  credentialPublicKey: Uint8Array,
  counter: number
): Promise<{ verified: boolean; authenticationInfo?: any; error?: string }> {
  try {
    // Convert Uint8Array to base64url string for SimpleWebAuthn v13+
    const credentialIdBase64url = Buffer.from(credentialID).toString('base64url');
    
    const opts: VerifyAuthenticationResponseOpts = {
      response,
      expectedChallenge,
      expectedOrigin,
      expectedRPID: MFA_CONFIG.WEBAUTHN_RP_ID,
      credential: {
        id: credentialIdBase64url,
        publicKey: new Uint8Array(credentialPublicKey),
        counter
      },
      requireUserVerification: true,
    };

    const verification = await verifyAuthenticationResponse(opts);
    return {
      verified: verification.verified,
      authenticationInfo: verification.authenticationInfo,
    };
  } catch (error) {
    console.error('Error verifying WebAuthn authentication:', error);
    return {
      verified: false,
      error: error instanceof Error ? error.message : 'Authentication failed',
    };
  }
}