// Environment configuration with fail-fast validation
export const MFA_CONFIG = {
  // WebAuthn config is resolved lazily through getWebAuthnConfig() so that
  // the wizard's PUBLIC_APP_URL setting flows through automatically.
  get WEBAUTHN_RP_ID() { return getWebAuthnConfig().rpId; },
  get WEBAUTHN_RP_NAME() { return getWebAuthnConfig().rpName; },
  get WEBAUTHN_ORIGIN() { return getWebAuthnConfig().origin; },
  // Resolve ENCRYPTION_KEY at call time (not at module load) so secrets
  // generated by the first-run setup wizard — which runs before any DB —
  // become immediately usable in subsequent wizard steps without requiring
  // a process restart. Validation logs once on first successful read.
  get ENCRYPTION_KEY(): string {
    const key = process.env.ENCRYPTION_KEY;
    if (!key) return '';
    if (key.length !== 64 || !/^[0-9a-fA-F]{64}$/.test(key)) return '';
    if (!_encryptionKeyLogged) {
      console.log('✅ MFA encryption key validated successfully');
      _encryptionKeyLogged = true;
    }
    return key;
  }
};

let _encryptionKeyLogged = false;
// Hard-fail in production deployments at startup if the key is missing or
// malformed — preserves the original boot-time guarantee that
// MFA_CONFIG.ENCRYPTION_KEY (the IIFE) gave us before we made it lazy.
(() => {
  const isProd = process.env.NODE_ENV === 'production';
  const key = process.env.ENCRYPTION_KEY;
  if (isProd) {
    if (!key || key.length !== 64 || !/^[0-9a-fA-F]{64}$/.test(key)) {
      console.error('🚨 CRITICAL: ENCRYPTION_KEY missing or malformed in production.');
      console.error('   Generate with: openssl rand -hex 32');
      process.exit(1);
    }
  } else if (!key) {
    console.warn('⚠️  ENCRYPTION_KEY not set — MFA encryption disabled (dev/setup mode).');
  } else if (key.length !== 64 || !/^[0-9a-fA-F]{64}$/.test(key)) {
    console.warn('⚠️  ENCRYPTION_KEY malformed (must be 64 hex chars) — encryption disabled until corrected.');
  }
})();

// Encryption utilities using AES-256-GCM (FIXED)
export function encryptText(text: string): string {
  if (!MFA_CONFIG.ENCRYPTION_KEY) {
    throw new Error('ENCRYPTION_KEY not configured - cannot encrypt TOTP secrets');
  }
  
  const key = Buffer.from(MFA_CONFIG.ENCRYPTION_KEY, 'hex');
  const iv = crypto.randomBytes(12); // 12 bytes for GCM
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  
  let encrypted = cipher.update(text, 'utf8', 'hex');
  encrypted += cipher.final('hex');
  
  const authTag = cipher.getAuthTag();
  
  return `${iv.toString('hex')}:${encrypted}:${authTag.toString('hex')}`;
}

// AES-256-GCM decrypt with an explicit hex key. Shared by decryptText
// and the fallback retry path below so the wire format
// (`iv:cipher:tag` hex) stays in exactly one place.
function decryptTextWithKeyHex(encryptedText: string, keyHex: string): string {
  const [ivHex, encrypted, authTagHex] = encryptedText.split(':');
  if (!ivHex || !encrypted || !authTagHex) {
    throw new Error('Invalid encrypted text format');
  }

  const key = Buffer.from(keyHex, 'hex');
  const iv = Buffer.from(ivHex, 'hex');
  const authTag = Buffer.from(authTagHex, 'hex');

  const decipher = crypto.createDecipheriv('aes-256-gcm', key, iv, { authTagLength: 16 });
  decipher.setAuthTag(authTag);

  let decrypted = decipher.update(encrypted, 'hex', 'utf8');
  decrypted += decipher.final('utf8');

  return decrypted;
}

export function decryptText(encryptedText: string): string {
  if (!MFA_CONFIG.ENCRYPTION_KEY) {
    throw new Error('ENCRYPTION_KEY not configured - cannot decrypt TOTP secrets');
  }

  try {
    return decryptTextWithKeyHex(encryptedText, MFA_CONFIG.ENCRYPTION_KEY);
  } catch (primaryErr) {
    // Dual-key window: during the brief interval the ENCRYPTION_KEY
    // rotation handler holds open between the re-encryption COMMIT
    // and the process.env swap (see server/routes/system-routes.ts), the
    // primary key may not match the row in front of us. Retry with
    // the registered fallback before surfacing the error so the
    // rotation window does not bubble up as a transient
    // "Unsupported state or unable to authenticate data" / "Invalid
    // encrypted text format" decode failure to whichever request
    // happened to land mid-rotation.
    //
    // In the steady state (no rotation in flight) the fallback slot
    // is null and we re-throw the primary error unchanged — so the
    // hot path stays a single decipher attempt.
    const fallback = getFallbackEncryptionKey();
    if (
      fallback &&
      fallback !== MFA_CONFIG.ENCRYPTION_KEY &&
      fallback.length === 64 &&
      /^[0-9a-fA-F]{64}$/.test(fallback)
    ) {
      try {
        return decryptTextWithKeyHex(encryptedText, fallback);
      } catch {
        // Fall through to the primary error so the caller sees the
        // exception that matches their current process.env key,
        // rather than a misleading fallback-key decode error.
      }
    }
    throw primaryErr;
  }
}

