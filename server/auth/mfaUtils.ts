// WebAuthn utilities using SimpleWebAuthn library
export interface WebAuthnOptions {
  rpID: string;
  rpName: string;
  origin: string;
}

export interface PasskeyRegistrationOptions {
  challenge: string;
  rp: {
    id: string;
    name: string;
  };
  user: {
    id: string;
    name: string;
    displayName: string;
  };
  pubKeyCredParams: Array<{
    alg: number;
    type: string;
  }>;
  authenticatorSelection: {
    authenticatorAttachment: string;
    userVerification: string;
  };
  timeout: number;
  attestation: string;
}

export async function generateWebAuthnRegistrationOptions(
  userId: string, 
  userName: string, 
  userDisplayName: string,
  excludeCredentials: string[] = []
): Promise<PasskeyRegistrationOptions> {
  try {
    const opts: GenerateRegistrationOptionsOpts = {
      rpName: MFA_CONFIG.WEBAUTHN_RP_NAME,
      rpID: MFA_CONFIG.WEBAUTHN_RP_ID,
      userID: Uint8Array.from(Buffer.from(userId, 'utf8')),
      userName: userName,
      userDisplayName: userDisplayName,
      timeout: 60000,
      attestationType: 'none',
      excludeCredentials: excludeCredentials.map(id => ({
        id: id, // SimpleWebAuthn expects base64url string ID
        type: 'public-key' as const,
        transports: ['internal', 'usb', 'ble', 'nfc', 'hybrid'],
      })),
      authenticatorSelection: {
        authenticatorAttachment: 'platform',
        userVerification: 'required',
      },
      supportedAlgorithmIDs: [-7, -257],
    };

    const options = await generateRegistrationOptions(opts);
    return options as PasskeyRegistrationOptions;
  } catch (error) {
    console.error('Error generating WebAuthn registration options:', error);
    throw new Error('Failed to generate WebAuthn registration options');
  }
}

export async function verifyWebAuthnRegistration(
  response: any,
  expectedChallenge: string,
  expectedOrigin: string
): Promise<{ verified: boolean; registrationInfo?: any; error?: string }> {
  try {
    const opts: VerifyRegistrationResponseOpts = {
      response,
      expectedChallenge,
      expectedOrigin,
      expectedRPID: MFA_CONFIG.WEBAUTHN_RP_ID,
      requireUserVerification: true,
    };

    const verification = await verifyRegistrationResponse(opts);
    return {
      verified: verification.verified,
      registrationInfo: verification.registrationInfo,
    };
  } catch (error) {
    console.error('Error verifying WebAuthn registration:', error);
    return {
      verified: false,
      error: error instanceof Error ? error.message : 'Verification failed',
    };
  }
}

