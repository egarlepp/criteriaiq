// Recovery code utilities - Generate high-entropy recovery codes (FIXED)
export function generateRecoveryCodes(count: number = 10): string[] {
  const codes: string[] = [];
  for (let i = 0; i < count; i++) {
    // Generate 32-character codes with full 128-bit entropy
    // Format: XXXX-XXXX-XXXX-XXXX-XXXX-XXXX-XXXX-XXXX using hex
    const bytes = crypto.randomBytes(16); // 128 bits of entropy
    const hex = bytes.toString('hex').toUpperCase();
    // Format as groups of 4 characters with dashes (8 groups total)
    const code = hex
      .replace(/(.{4})/g, '$1-')
      .slice(0, -1); // Remove trailing dash
    codes.push(code);
  }
  return codes;
}

export async function hashRecoveryCode(code: string): Promise<string> {
  return await bcrypt.hash(code, 10);
}

export async function verifyRecoveryCode(code: string, hash: string): Promise<boolean> {
  return await bcrypt.compare(code, hash);
}

// Match a submitted recovery code against the caller's unused stored
// hashes. Extracted from the /api/mfa/challenge handler so the
// matching+replay-protection contract can be unit-tested without
// mounting the full Express stack (Task #595).
//
// Callers MUST pre-filter `candidates` to rows whose `usedAt` is
// still NULL — that DB filter is what makes a successful match
// non-replayable, and we mirror it here by returning `null` whenever
// the candidate list is empty (i.e. the code has already been
// consumed). The handler then marks the returned id's `usedAt` so
// the next /api/mfa/challenge call with the same code finds no
// unused candidates and falls into the same `null` branch.
export async function findMatchingUnusedRecoveryCode(
  candidates: Array<{ id: string; codeHash: string }>,
  submittedCode: string,
): Promise<{ id: string } | null> {
  if (!submittedCode) return null;
  for (const candidate of candidates) {
    if (await verifyRecoveryCode(submittedCode, candidate.codeHash)) {
      return { id: candidate.id };
    }
  }
  return null;
}

// Recovery-code low-water threshold used by /api/mfa/challenge to
// nudge operators to regenerate before they end up locked out
// (Task #602). Pinned as an exported constant so the route, the
// frontend prompt, and the regression test all read from a single
// source of truth — bumping it in one place must change behaviour
// everywhere it matters.
export const RECOVERY_CODES_LOW_THRESHOLD = 3;

export interface RecoveryCodesWarning {
  recoveryCodesRemaining: number;
  recoveryCodesLow: boolean;
}

// Pure helper so the threshold contract can be unit-tested without
// standing up the full /api/mfa/challenge harness. The route calls
// this AFTER it has marked the matched recovery row's `usedAt`, so
// `remaining` already reflects the post-consumption count the
// operator will see when they try the next recovery login.
//
// Negative inputs are clamped to 0 — the count comes from a SQL
// `COUNT(*)`, but a defensive clamp keeps the contract robust if a
// future caller ever passes a stale or off-by-one value. `low` is
// strictly `<` the threshold so a fresh batch of exactly 3 codes is
// not treated as low; the prompt only fires once the operator has
// burned through enough that the next loss is genuinely risky.
export function evaluateRecoveryCodesWarning(remaining: number): RecoveryCodesWarning {
  const safeRemaining = Number.isFinite(remaining) && remaining > 0 ? Math.floor(remaining) : 0;
  return {
    recoveryCodesRemaining: safeRemaining,
    recoveryCodesLow: safeRemaining < RECOVERY_CODES_LOW_THRESHOLD,
  };
}

