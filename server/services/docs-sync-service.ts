const GITHUB_RAW_BASE = "https://raw.githubusercontent.com";
const GITHUB_API_BASE = "https://api.github.com";

interface GitHubTreeItem {
  path: string;
  mode: string;
  type: string;
  sha: string;
  size?: number;
  url: string;
}

interface SidebarNode {
  key: string;
  label: string;
  type: "category" | "doc" | "link";
  docPath?: string;
  children?: SidebarNode[];
}

function estimateTokens(text: string): number {
  return Math.ceil(text.length / 4);
}

function extractTitle(markdown: string): string {
  const frontmatterMatch = markdown.match(/^---[\s\S]*?title:\s*["']?(.+?)["']?\s*$/m);
  if (frontmatterMatch) return frontmatterMatch[1].trim();
  const h1Match = markdown.match(/^#\s+(.+)$/m);
  if (h1Match) return h1Match[1].trim();
  const sidebarMatch = markdown.match(/sidebar_label:\s*["']?(.+?)["']?\s*$/m);
  if (sidebarMatch) return sidebarMatch[1].trim();
  return "";
}

function stripFrontmatter(markdown: string): string {
  return markdown.replace(/^---[\s\S]*?---\s*/, "").trim();
}

function contentHash(content: string): string {
  return crypto.createHash("sha256").update(content).digest("hex");
}

async function githubFetch(url: string): Promise<Response> {
  const headers: Record<string, string> = {
    "Accept": "application/vnd.github.v3+json",
    "User-Agent": "CriteriaIQ-DocSync",
  };
  const token = process.env.GITHUB_TOKEN;
  if (token) {
    headers["Authorization"] = `Bearer ${token}`;
  }
  return fetch(url, { headers });
}

export async function fetchRepoTree(owner: string, repo: string, branch: string, path: string): Promise<GitHubTreeItem[]> {
  const url = `${GITHUB_API_BASE}/repos/${owner}/${repo}/git/trees/${branch}?recursive=1`;
  const response = await githubFetch(url);
  if (!response.ok) {
    throw new Error(`GitHub API error: ${response.status} ${response.statusText}`);
  }
  const data = await response.json() as { tree: GitHubTreeItem[] };
  return data.tree.filter((item: GitHubTreeItem) =>
    item.path.startsWith(path) &&
    item.type === "blob" &&
    (item.path.endsWith(".md") || item.path.endsWith(".mdx"))
  );
}

export async function fetchFileContent(owner: string, repo: string, branch: string, filePath: string): Promise<string> {
  const url = `${GITHUB_RAW_BASE}/${owner}/${repo}/${branch}/${filePath}`;
  const response = await fetch(url, {
    headers: { "User-Agent": "CriteriaIQ-DocSync" },
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${filePath}: ${response.status}`);
  }
  return response.text();
}

export async function fetchSidebarStructure(owner: string, repo: string, branch: string, sidebarPath: string): Promise<string> {
  return fetchFileContent(owner, repo, branch, sidebarPath);
}

export function parseSidebarJs(sidebarContent: string, docsBasePath: string): SidebarNode[] {
  const nodes: SidebarNode[] = [];

  function parseItems(items: any[], parentKey: string = ""): SidebarNode[] {
    const result: SidebarNode[] = [];
    if (!Array.isArray(items)) return result;

    for (let i = 0; i < items.length; i++) {
      const item = items[i];
      if (typeof item === "string") {
        const key = parentKey ? `${parentKey}/${item}` : item;
        result.push({
          key,
          label: item.split("/").pop()?.replace(/-/g, " ").replace(/\b\w/g, (l: string) => l.toUpperCase()) || item,
          type: "doc",
          docPath: `${docsBasePath}/${item}.md`,
        });
      } else if (item && typeof item === "object") {
        if (item.type === "category" || item.items) {
          const label = item.label || "Unknown";
          const key = parentKey ? `${parentKey}/${label.toLowerCase().replace(/\s+/g, "-")}` : label.toLowerCase().replace(/\s+/g, "-");
          const children = parseItems(item.items || [], key);
          result.push({
            key,
            label,
            type: "category",
            children,
          });
        } else if (item.type === "doc" || item.id) {
          const id = item.id || item.slug || "";
          const key = parentKey ? `${parentKey}/${id}` : id;
          result.push({
            key,
            label: item.label || id.split("/").pop()?.replace(/-/g, " ") || id,
            type: "doc",
            docPath: `${docsBasePath}/${id}.md`,
          });
        } else if (item.type === "autogenerated") {
          const dirName = item.dirName || ".";
          const key = parentKey ? `${parentKey}/__auto_${dirName}` : `__auto_${dirName}`;
          result.push({
            key,
            label: `Auto: ${dirName === "." ? "All" : dirName}`,
            type: "category",
            docPath: `${docsBasePath}/${dirName === "." ? "" : dirName}`,
          });
        }
      }
    }
    return result;
  }

  try {
    const sidebarMatch = sidebarContent.match(/sidebar\s*:\s*(\[[\s\S]*?\])\s*[,}]/);
    if (sidebarMatch) {
      try {
        const cleanedArray = sidebarMatch[1]
          .replace(/\/\/.*/g, "")
          .replace(/\/\*[\s\S]*?\*\//g, "")
          .replace(/,\s*([}\]])/g, "$1")
          .replace(/(\w+)\s*:/g, '"$1":');
        const parsed = JSON.parse(cleanedArray);
        return parseItems(parsed);
      } catch {
      }
    }

    const categoryRegex = /\{\s*type:\s*['"]category['"]\s*,\s*label:\s*['"]([^'"]+)['"]\s*,/g;
    let match;
    while ((match = categoryRegex.exec(sidebarContent)) !== null) {
      nodes.push({
        key: match[1].toLowerCase().replace(/\s+/g, "-"),
        label: match[1],
        type: "category",
      });
    }

    const autogenRegex = /type:\s*['"]autogenerated['"]\s*,\s*dirName:\s*['"]([^'"]+)['"]/g;
    while ((match = autogenRegex.exec(sidebarContent)) !== null) {
      const dirName = match[1];
      nodes.push({
        key: `__auto_${dirName}`,
        label: dirName === "." ? "All Documentation" : dirName.replace(/-/g, " ").replace(/\b\w/g, (l: string) => l.toUpperCase()),
        type: "category",
        docPath: `${docsBasePath}/${dirName === "." ? "" : dirName}`,
      });
    }

    if (nodes.length === 0) {
      nodes.push({
        key: "__auto_all",
        label: "All Documentation",
        type: "category",
        docPath: docsBasePath,
      });
    }
  } catch (error) {
    console.error("Error parsing sidebar:", error);
    nodes.push({
      key: "__auto_all",
      label: "All Documentation",
      type: "category",
      docPath: docsBasePath,
    });
  }

  return nodes;
}

export async function buildSidebarFromFileTree(
  owner: string,
  repo: string,
  branch: string,
  docsPath: string
): Promise<SidebarNode[]> {
  const files = await fetchRepoTree(owner, repo, branch, docsPath);
  const tree: Record<string, SidebarNode> = {};
  const roots: SidebarNode[] = [];

  const sortedFiles = files
    .map(f => f.path.replace(docsPath + "/", ""))
    .filter(p => !p.startsWith("_") && p !== "index.md" && p !== "index.mdx")
    .sort();

  for (const relativePath of sortedFiles) {
    const parts = relativePath.split("/");
    let currentParentKey = "";

    for (let i = 0; i < parts.length; i++) {
      const part = parts[i];
      const isFile = i === parts.length - 1;
      const key = currentParentKey ? `${currentParentKey}/${part}` : part;

      if (isFile) {
        const cleanName = part.replace(/\.(md|mdx)$/, "");
        if (cleanName === "index") continue;
        const node: SidebarNode = {
          key,
          label: cleanName.replace(/-/g, " ").replace(/\b\w/g, (l: string) => l.toUpperCase()),
          type: "doc",
          docPath: `${docsPath}/${relativePath}`,
        };
        if (currentParentKey && tree[currentParentKey]) {
          if (!tree[currentParentKey].children) tree[currentParentKey].children = [];
          tree[currentParentKey].children!.push(node);
        } else {
          roots.push(node);
        }
        tree[key] = node;
      } else {
        if (!tree[key]) {
          const catNode: SidebarNode = {
            key,
            label: part.replace(/-/g, " ").replace(/\b\w/g, (l: string) => l.toUpperCase()),
            type: "category",
            children: [],
          };
          tree[key] = catNode;
          if (currentParentKey && tree[currentParentKey]) {
            if (!tree[currentParentKey].children) tree[currentParentKey].children = [];
            tree[currentParentKey].children!.push(catNode);
          } else {
            roots.push(catNode);
          }
        }
        currentParentKey = key;
      }
    }
  }

  return roots;
}

function flattenSidebarNodes(nodes: SidebarNode[], parentKey: string | null = null, depth: number = 0): Array<{
  nodeKey: string;
  label: string;
  parentKey: string | null;
  nodeType: string;
  docPath: string | null;
  position: number;
  depth: number;
}> {
  const flat: Array<any> = [];
  for (let i = 0; i < nodes.length; i++) {
    const node = nodes[i];
    flat.push({
      nodeKey: node.key,
      label: node.label,
      parentKey: parentKey,
      nodeType: node.type,
      docPath: node.docPath || null,
      position: i,
      depth,
    });
    if (node.children && node.children.length > 0) {
      flat.push(...flattenSidebarNodes(node.children, node.key, depth + 1));
    }
  }
  return flat;
}

export async function syncRepositoryDocs(configId: number): Promise<{
  status: string;
  pagesAdded: number;
  pagesUpdated: number;
  pagesTotal: number;
  message: string;
}> {
  const [config] = await db.select().from(docsRepositoryConfigs).where(eq(docsRepositoryConfigs.id, configId));
  if (!config) throw new Error(`Config ${configId} not found`);

  const result = { status: "success", pagesAdded: 0, pagesUpdated: 0, pagesTotal: 0, message: "" };

  try {
    let sidebarNodes: SidebarNode[];
    if (config.sidebarPath) {
      try {
        const sidebarContent = await fetchFileContent(config.repoOwner, config.repoName, config.branch, config.sidebarPath);
        sidebarNodes = parseSidebarJs(sidebarContent, config.docsPath);
      } catch {
        sidebarNodes = await buildSidebarFromFileTree(config.repoOwner, config.repoName, config.branch, config.docsPath);
      }
    } else {
      sidebarNodes = await buildSidebarFromFileTree(config.repoOwner, config.repoName, config.branch, config.docsPath);
    }

    await db.delete(docsSidebarStructure).where(eq(docsSidebarStructure.repoConfigId, configId));
    const flatNodes = flattenSidebarNodes(sidebarNodes);
    if (flatNodes.length > 0) {
      for (const node of flatNodes) {
        await db.insert(docsSidebarStructure).values({
          repoConfigId: configId,
          ...node,
        });
      }
    }

    const files = await fetchRepoTree(config.repoOwner, config.repoName, config.branch, config.docsPath);
    const existingCache = await db.select().from(docsContentCache).where(eq(docsContentCache.repoConfigId, configId));
    const existingMap = new Map(existingCache.map(c => [c.filePath, c]));

    for (const file of files) {
      try {
        const existing = existingMap.get(file.path);
        if (existing && existing.lastCommitSha === file.sha) {
          result.pagesTotal++;
          continue;
        }

        const content = await fetchFileContent(config.repoOwner, config.repoName, config.branch, file.path);
        const cleanContent = stripFrontmatter(content);
        const title = extractTitle(content);
        const hash = contentHash(cleanContent);

        if (existing) {
          if (existing.contentHash !== hash) {
            await db.update(docsContentCache)
              .set({
                content: cleanContent,
                title: title || existing.title,
                contentHash: hash,
                tokenEstimate: estimateTokens(cleanContent),
                lastCommitSha: file.sha,
                lastModifiedAt: new Date(),
                updatedAt: new Date(),
              })
              .where(eq(docsContentCache.id, existing.id));
            result.pagesUpdated++;
          }
        } else {
          await db.insert(docsContentCache).values({
            repoConfigId: configId,
            filePath: file.path,
            title: title || file.path.split("/").pop()?.replace(/\.(md|mdx)$/, "") || "",
            content: cleanContent,
            contentHash: hash,
            tokenEstimate: estimateTokens(cleanContent),
            lastCommitSha: file.sha,
            lastModifiedAt: new Date(),
          });
          result.pagesAdded++;
        }
        result.pagesTotal++;

        await new Promise(resolve => setTimeout(resolve, 100));
      } catch (err) {
        console.error(`Error syncing file ${file.path}:`, err);
      }
    }

    await db.update(docsRepositoryConfigs)
      .set({
        lastSyncAt: new Date(),
        lastSyncStatus: "success",
        lastSyncMessage: `Synced ${result.pagesTotal} pages (${result.pagesAdded} new, ${result.pagesUpdated} updated)`,
        totalPages: result.pagesTotal,
        updatedAt: new Date(),
      })
      .where(eq(docsRepositoryConfigs.id, configId));

    result.message = `Successfully synced ${result.pagesTotal} pages`;
  } catch (error: any) {
    result.status = "error";
    result.message = error.message || "Unknown error during sync";

    await db.update(docsRepositoryConfigs)
      .set({
        lastSyncAt: new Date(),
        lastSyncStatus: "error",
        lastSyncMessage: result.message,
        updatedAt: new Date(),
      })
      .where(eq(docsRepositoryConfigs.id, configId));
  }

  return result;
}

export async function syncAllRepositories(): Promise<{
  total: number;
  succeeded: number;
  failed: number;
  results: Array<{ configId: number; productId: number; status: string; message: string }>;
}> {
  const configs = await db.select().from(docsRepositoryConfigs).where(eq(docsRepositoryConfigs.isActive, true));
  const results: Array<{ configId: number; productId: number; status: string; message: string }> = [];

  for (const config of configs) {
    try {
      const syncResult = await syncRepositoryDocs(config.id);
      results.push({
        configId: config.id,
        productId: config.productId,
        status: syncResult.status,
        message: syncResult.message,
      });
    } catch (error: any) {
      results.push({
        configId: config.id,
        productId: config.productId,
        status: "error",
        message: error.message,
      });
    }
  }

  const schedule = await db.select().from(docsSyncSchedule).limit(1);
  if (schedule.length > 0) {
    const intervalHours = schedule[0].syncIntervalHours;
    const nextRun = new Date(Date.now() + intervalHours * 60 * 60 * 1000);
    await db.update(docsSyncSchedule)
      .set({
        lastRunAt: new Date(),
        nextRunAt: nextRun,
        lastRunStatus: results.every(r => r.status === "success") ? "success" : "partial",
        lastRunMessage: `Synced ${results.filter(r => r.status === "success").length}/${results.length} repositories`,
        updatedAt: new Date(),
      })
      .where(eq(docsSyncSchedule.id, schedule[0].id));
  }

  return {
    total: results.length,
    succeeded: results.filter(r => r.status === "success").length,
    failed: results.filter(r => r.status === "error").length,
    results,
  };
}

export async function getDocContentForAssessment(
  productId: number,
  selectedDocKeys: string[]
): Promise<{ sections: Array<{ title: string; content: string; path: string }>; totalTokens: number }> {
  if (!selectedDocKeys || selectedDocKeys.length === 0) {
    return { sections: [], totalTokens: 0 };
  }

  const configs = await db.select().from(docsRepositoryConfigs)
    .where(and(
      eq(docsRepositoryConfigs.productId, productId),
      eq(docsRepositoryConfigs.isActive, true),
    ));

  if (configs.length === 0) {
    return { sections: [], totalTokens: 0 };
  }

  const configIds = configs.map(c => c.id);
  const sections: Array<{ title: string; content: string; path: string }> = [];
  let totalTokens = 0;
  const MAX_TOKENS = 15000;

  for (const configId of configIds) {
    const sidebarNodes = await db.select().from(docsSidebarStructure)
      .where(eq(docsSidebarStructure.repoConfigId, configId));

    const matchingDocPaths = new Set<string>();
    for (const key of selectedDocKeys) {
      const matchingNodes = sidebarNodes.filter(n =>
        n.nodeKey === key || n.nodeKey.startsWith(key + "/")
      );
      for (const node of matchingNodes) {
        if (node.docPath) matchingDocPaths.add(node.docPath);
      }

      if (matchingNodes.some(n => n.nodeType === "category")) {
        const childNodes = sidebarNodes.filter(n =>
          n.parentKey === key || n.nodeKey.startsWith(key + "/")
        );
        for (const child of childNodes) {
          if (child.docPath) matchingDocPaths.add(child.docPath);
        }
      }
    }

    for (const docPath of matchingDocPaths) {
      if (totalTokens >= MAX_TOKENS) break;

      const cached = await db.select().from(docsContentCache)
        .where(and(
          eq(docsContentCache.repoConfigId, configId),
          eq(docsContentCache.filePath, docPath),
        ))
        .limit(1);

      if (cached.length > 0 && cached[0].content) {
        const tokens = cached[0].tokenEstimate || estimateTokens(cached[0].content);
        let content = cached[0].content;
        if (totalTokens + tokens > MAX_TOKENS) {
          const remainingTokens = MAX_TOKENS - totalTokens;
          const charLimit = remainingTokens * 4;
          content = content.substring(0, charLimit) + "\n\n[Content truncated for token budget]";
        }
        sections.push({
          title: cached[0].title || docPath,
          content,
          path: docPath,
        });
        totalTokens += Math.min(tokens, MAX_TOKENS - totalTokens + tokens);
      }
    }
  }

  return { sections, totalTokens };
}

/** Key on Configuration › Scheduler. */
export const DOCS_SYNC_JOB_KEY = "docs_sync";
const HOUR_MS = 60 * 60 * 1000;

/**
 * Register the docs sync with the shared Scheduler (Configuration ›
 * Scheduler), which owns its cadence and on/off switch. The default
 * cadence is still `docs_sync_schedule.sync_interval_hours` (24 h), and as
 * before the first sync waits one full interval after boot.
 */
export async function startDocsSyncScheduler(): Promise<void> {
  try {
    let schedule = await db.select().from(docsSyncSchedule).limit(1);
    if (schedule.length === 0) {
      await db.insert(docsSyncSchedule).values({
        syncIntervalHours: 24,
        isEnabled: true,
        nextRunAt: new Date(Date.now() + 24 * HOUR_MS),
      });
      schedule = await db.select().from(docsSyncSchedule).limit(1);
    }

    // NOTE (Task #720): Intentionally do NOT seed an `email_schedules` row
    // for `docs_sync` at boot. Operators expect Workflow Automation's
    // schedule list to be empty after install and add their own.

    const intervalHours = schedule[0]?.syncIntervalHours || 24;
    scheduleJob({
      key: DOCS_SYNC_JOB_KEY,
      category: "system",
      label: "Documentation sync",
      defaultIntervalMs: intervalHours * HOUR_MS,
      cadenceEditable: true,
      minIntervalMs: HOUR_MS,
      task: async () => {
        const { dbHealth } = await import("../lib/db-probe");
        if (!dbHealth.reachable) return { status: "skipped", message: "database_unreachable" };
        console.log("[Docs Sync] Running scheduled sync...");
        const result = await syncAllRepositories();
        console.log("[Docs Sync] Scheduled sync complete");
        if (result.total === 0) return { status: "skipped", message: "no_repositories" };
        if (result.failed > 0 && result.succeeded === 0) {
          throw new Error(`All ${result.failed} documentation repositories failed to sync`);
        }
        return {
          status: "success",
          itemsProcessed: result.succeeded,
          message: result.failed > 0 ? `${result.failed} of ${result.total} repositories failed` : undefined,
        };
      },
    });

    console.log(`[Docs Sync] Registered with the Scheduler (default every ${intervalHours}h)`);
  } catch (error) {
    console.error("[Docs Sync] Failed to start scheduler:", error);
  }
}

/**
 * PUT /api/docs-sync/schedule. Saves the interval on the docs_sync_schedule
 * row (still shown on the Documentation Sources page) and on the Scheduler,
 * which is what actually runs the sync.
 */
export async function updateSyncSchedule(intervalHours: number, isEnabled: boolean, userId?: string): Promise<void> {
  const existing = await db.select().from(docsSyncSchedule).limit(1);
  const nextRunAt = isEnabled ? new Date(Date.now() + intervalHours * HOUR_MS) : null;
  if (existing.length > 0) {
    await db.update(docsSyncSchedule)
      .set({
        syncIntervalHours: intervalHours,
        isEnabled,
        nextRunAt,
        configuredBy: userId || existing[0].configuredBy,
        updatedAt: new Date(),
      })
      .where(eq(docsSyncSchedule.id, existing[0].id));
  } else {
    await db.insert(docsSyncSchedule).values({
      syncIntervalHours: intervalHours,
      isEnabled,
      nextRunAt,
      configuredBy: userId,
    });
  }

  const { storage } = await import("../storage");
  const row = await storage.upsertJobConfig(
    DOCS_SYNC_JOB_KEY,
    { enabled: isEnabled, intervalMs: intervalHours * HOUR_MS },
    userId ?? null,
  );
  applyJobConfig(DOCS_SYNC_JOB_KEY, { enabled: row.enabled, intervalMs: row.intervalMs });
}
